function updateCopy(copy) {
  const id = copy?.source?.resourceId;
  if (copy?.source?.packageId !== '01a17c40-0000-7000-8000-000000000002' || !updates[id]) return copy;
  if (JSON.stringify(copy.data.内容) !== JSON.stringify(previous[id])) return copy;
  return { ...copy, data: { ...copy.data, 内容: updates[id] } };
}

module.exports = ({ characterData }) => {
  const table = characterData['character-card-table'];
  if (!table || !Array.isArray(table.instances)) return characterData;
  const instances = table.instances.map(instance => ({
    ...instance,
    resourceCopy: updateCopy(instance.resourceCopy),
    ...(instance.backResourceCopy ? { backResourceCopy: updateCopy(instance.backResourceCopy) } : {}),
  }));
  return { ...characterData, 'character-card-table': { ...table, instances } };
};
