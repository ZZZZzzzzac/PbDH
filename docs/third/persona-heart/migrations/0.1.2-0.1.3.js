module.exports = ({ characterData }) => {
  const table = characterData['character-card-table'];
  if (!table || !Array.isArray(table.instances)) return characterData;
  const packageId = '01a17c40-0000-7000-8000-000000000002';
  const instances = table.instances.map((instance) => {
    const copy = instance.resourceCopy;
    const id = copy?.source?.resourceId;
    if (copy?.source?.packageId !== packageId || !definitions[id]) return instance;
    const wasBack = instance.geometry.flipped;
    const visibleId = wasBack ? definitions[id].targetId : id;
    const definition = definitions[visibleId];
    // 未翻面的卡保留玩家编辑过的正文；旧背面仍采用原系统包对应卡面。
    const data = { ...(wasBack ? definition.data : copy.data) };
    delete data['另一面'];
    return {
      ...instance,
      resourceCopy: {
        ...copy,
        source: { ...copy.source, resourceId: visibleId },
        data,
        replacements: [{ replacementId: 'alternate-form', targetResourceId: definition.targetId }],
      },
      geometry: { ...instance.geometry, flipped: false },
    };
  });
  return { ...characterData, 'character-card-table': { ...table, instances } };
};
